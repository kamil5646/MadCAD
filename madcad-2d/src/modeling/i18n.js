export function resolveModelingLanguage(documentLanguage, desktopLanguage) {
  const candidate = String(documentLanguage || desktopLanguage || '').toLowerCase();
  return candidate.startsWith('en') ? 'en' : 'pl';
}

export function translateModelingText(value, language = 'pl') {
  const source = String(value ?? '');
  if (language !== 'en' || !source.trim()) return source;
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const normalized = source.trim();
  if (ENGLISH_TEXT[normalized]) return `${leading}${ENGLISH_TEXT[normalized]}${trailing}`;
  if (ENGLISH_TEXT[`${normalized}.`]) return `${leading}${ENGLISH_TEXT[`${normalized}.`].replace(/\.$/, '')}${trailing}`;
  const shortcut = normalized.match(/^(.*) Skrót: (.*)\.$/);
  if (shortcut) {
    const separator = shortcut[1].indexOf('. ');
    const content = separator > 0
      ? `${translateModelingText(shortcut[1].slice(0, separator), language).trim()}. ${translateModelingText(shortcut[1].slice(separator + 2), language).trim()}`
      : translateModelingText(shortcut[1], language).trim();
    return `${leading}${content} Shortcut: ${shortcut[2]}.${trailing}`;
  }
  const separator = normalized.indexOf('. ');
  if (separator > 0) {
    const first = normalized.slice(0, separator);
    const rest = normalized.slice(separator + 2);
    const translatedFirst = translateModelingText(first, language).trim();
    const translatedRest = translateModelingText(rest, language).trim();
    if (translatedFirst !== first || translatedRest !== rest) {
      return `${leading}${translatedFirst}. ${translatedRest}${trailing}`;
    }
  }
  return ENGLISH_PHRASES.reduce((text, [pattern, replacement]) => text.replace(pattern, replacement), source);
}

const POLISH_INTERFACE_PATTERN = /(?:[ąćęłńóśźż]|\b(?:Zaznacz|Wybierz|Pokaż|Ukryj|Nowy|Otwórz|Zapisz|Usuń|Cofnij|Ponów|Gotowe|Płaszczyzna|Parametry|Konstrukcja|Szkice|Bryły|Utwórz|Zaokrąglij|Fazuj|Przesuń|Obróć|Edytuj|Zamknij|Anuluj|Dodaj|Pominięto|Zmieniono|Sprawdź|Pozostałe|Niedowiązany|Dokumentacja|Arkusz|Właściwości|Orientacja|Kierunek|Skala|więz|układ|obszaru|poziomo|pionowo|wid)\b)/i;

export function findUntranslatedModelingText(root) {
  if (!root?.querySelectorAll) return [];
  const untranslated = new Set();
  const inspect = (value) => {
    const normalized = String(value || '').trim();
    if (normalized && POLISH_INTERFACE_PATTERN.test(normalized)) untranslated.add(normalized);
  };
  root.querySelectorAll('*').forEach((element) => {
    if (element.closest('[data-i18n-ignore="true"]')) return;
    if (!element.children.length && !['SCRIPT', 'STYLE'].includes(element.tagName)) inspect(element.textContent);
    for (const attribute of ['aria-label', 'title', 'placeholder']) inspect(element.getAttribute(attribute));
  });
  return [...untranslated];
}

function localizeElementAttributes(element, language) {
  if (!(element instanceof Element)) return;
  for (const attribute of ['aria-label', 'title', 'placeholder']) {
    const current = element.getAttribute(attribute);
    if (!current) continue;
    const translated = translateModelingText(current, language);
    if (translated !== current) element.setAttribute(attribute, translated);
  }
}

export function localizeModelingTree(root, language = 'pl') {
  if (!root || language !== 'en') return;
  localizeElementAttributes(root, language);
  root.querySelectorAll('*').forEach((element) => localizeElementAttributes(element, language));
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const translated = translateModelingText(node.nodeValue, language);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    node = walker.nextNode();
  }
}

export function observeModelingLocalization(root, language = 'pl') {
  if (!root || language !== 'en' || typeof MutationObserver === 'undefined') return () => {};
  localizeModelingTree(root, language);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        const translated = translateModelingText(mutation.target.nodeValue, language);
        if (translated !== mutation.target.nodeValue) mutation.target.nodeValue = translated;
      } else {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) {
            const translated = translateModelingText(node.nodeValue, language);
            if (translated !== node.nodeValue) node.nodeValue = translated;
          } else if (node.nodeType === Node.ELEMENT_NODE) localizeModelingTree(node, language);
        });
      }
    }
  });
  observer.observe(root, { childList: true, subtree: true, characterData: true });
  return () => observer.disconnect();
}
